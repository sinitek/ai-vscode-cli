#!/usr/bin/env bash
# 供 run_dev.sh / export_vscode_extension.sh source。
# 约定：仓库不提交 lockfile。本机可以是 npm 或 pnpm 布局，但禁止在 pnpm 树上直接 npm install。

workspace_has_pnpm_node_modules() {
  [[ -d node_modules/.pnpm ]]
}

install_workspace_node_modules() {
  if ! command -v npm >/dev/null 2>&1; then
    echo "npm 未安装或不在 PATH 中。" >&2
    return 1
  fi

  if workspace_has_pnpm_node_modules; then
    if command -v pnpm >/dev/null 2>&1; then
      echo "检测到 pnpm node_modules，使用 pnpm install。"
      pnpm install
      return 0
    fi
    echo "检测到 pnpm node_modules，但本机没有 pnpm。删除后改用 npm install。"
    rm -rf node_modules
  elif [[ ! -e node_modules ]] && [[ -f pnpm-lock.yaml ]] && command -v pnpm >/dev/null 2>&1; then
    echo "检测到本地 pnpm-lock.yaml，使用 pnpm install。"
    pnpm install
    return 0
  fi

  echo "使用 npm install。"
  npm install
}
